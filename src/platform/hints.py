# 문장 안 구절 (토스트·버튼 이름 등 문장이 조금씩 달라지는 곳)
PHRASES = [
    (" (Tab)", ""), (" (B)", ""), (" (M)", ""), (" (C)", ""),
    ("(M: 지도)", "(가방 → 지도)"), ("(C: 열기)", "(가방 → 보물상자)"),
    ("B: 상점에서", "가방 → 상점에서"), ("지도(M)", "지도"),
    ("우클릭으로 회수", "회수 버튼으로 걷기"), ("(우클릭: 회수)", "(회수 버튼)"),
    ("클릭해서 계속", "탭해서 계속"), ("한 번 더 클릭", "한 번 더 탭"), ("클릭: ", "탭: "),
    ("순간 좌클릭!", "순간 탭!"), ("1키로 사용", "'도구' 버튼으로 사용"), ("2키로 사용", "'도구' 버튼으로 사용"),
]


def localize(s: str) -> str:
    if not IS_MOBILE or not s:
        return s
    if s in EXACT:
        return EXACT[s]
    for a, b in PHRASES:
        if a in s:
            s = s.replace(a, b)
    return s
