"""산신 쏘가리 '산군' 전투 곡 — 새 작곡 (음 하나하나를 직접 적은 데이터, DESIGN.md 43-28)

예전 L02-SANGUN 은 공통 연주법 + 다른 전설과 같은 틀의 주선율이라 일섬 · 여우비와 모양이 겹쳤다 (유사도 49% · 44%).
이 곡은 처음부터 새로: 몽골 초원의 말 달리기 = 점8분-16분 '말발굽' 리듬, 5음(E G A B D) 안의 4도 · 5도 · 옥타브 도약, 같은 음 되풀이,
긴 소리 끝에 떨어지는 꼬리 — 계단식 순차 진행은 피함.

E 5음 단조 · 156 · 4/4
  인트로  1마디  호랑이 울음 '어흥' + 큰 북 + 손북 굴림 → 외침 '하!'
  1페이즈 16마디 (산의 주인이 나타남)  마두금 주선율 + 낮은 마두금 말발굽 + 목 노래 지속음 + 큰 북 · 손북 · 낮은 북
                   1마디 주인의 동기 (E → B → A)
  2페이즈 16마디 (방향 전환 두 번씩)  마두금이 묻고 목 노래 휘파람이 두 번씩 대답, 외침 '하!'
  3페이즈 16마디 (산군의 위엄)  뿔나팔이 큰 부름 + 마두금이 한 옥타브 아래 같이, 4마디마다 외침, 큰 북 말발굽 가득
  위기   낮은 북 8분 + 박마다 외침 (작곡된 그대로)
  전환   큰 북 16분 굴림 점점 세게 + 멀리서 울음 + 끝에 외침
  실패   호랑이 울음이 멀어지며 사라짐 + 낮은 북
사용: python tools/audio/compose_sangun.py  →  data/music/sangun_notes.json
"""
from notes_compose import Score, m

S = Score("산신 쏘가리 '산군'", 156)
B = 4
INTRO = 4
P1, P2, P3, END = INTRO, INTRO + 64, INTRO + 128, INTRO + 192
S.sigs = [(0, "4/4")]
S.markers = [(0, "intro"), (P1, "phase1"), (P2, "phase2"), (P3, "phase3"), (END, "end")]
S.loops = {"phase1": [P1, P2], "phase2": [P2, P3], "phase3": [P3, END]}
S.layers = {"throat": "base", "morin_low": "base", "morin": "lead", "horn": "lead", "whistle": "choir", "shout": "choir",
            "big": "perc", "hand": "perc", "low": "perc", "roar": "perc", "c_low": "perc", "c_shout": "perc"}
S.voices = {"throat": "mg_throat", "morin_low": "mg_morin", "morin": "mg_morin", "horn": "mg_horn", "whistle": "mg_whistle",
            "shout": "mg_shout", "c_shout": "mg_shout", "roar": "mg_roar", "big": "big", "hand": "hand", "low": "low", "c_low": "low"}
S.gains = {"throat": 0.75, "morin_low": 0.45, "morin": 0.62, "horn": 0.72, "whistle": 0.3, "shout": 0.5, "c_shout": 0.42,
           "roar": 0.55, "big": 0.9, "hand": 0.3, "low": 0.7, "c_low": 0.6}
S.pans = {"morin_low": -0.3, "morin": 0.1, "horn": -0.1, "whistle": 0.35, "shout": 0.15, "hand": 0.25, "low": -0.1}
S.rings = {"roar": 0.4, "shout": 0.2, "c_shout": 0.2}

ROOTS = {"E": "E", "D": "D", "G": "G", "A": "A", "B": "B"}


def low(r, octv):   # 뿌리음 이름 → 그 옥타브
    return m(f"{r}{octv}")


def drone(start, roots, vel=90):
    """목 노래 지속음: 마디마다 뿌리음 (같은 음이 이어지면 길게)."""
    b = 0
    while b < len(roots):
        e = b + 1
        while e < len(roots) and roots[e] == roots[b]:
            e += 1
        S.add("throat", start + b * B, (e - b) * B * 0.98, low(roots[b], 2), vel)
        b = e


def gallop(start, roots, vel=88, busy=False):
    """낮은 마두금 말발굽: 박마다 뿌리 (점8분) · 뿌리 (16분) — busy 면 둘째 · 넷째 박에 5도로 뛰어오름."""
    for b, r in enumerate(roots):
        rt = low(r, 3)
        for k in range(4):
            t = start + b * B + k
            S.add("morin_low", t, 0.7, rt, vel)
            S.add("morin_low", t + 0.75, 0.25, rt + (7 if busy and k % 2 == 1 else 0), vel - 14)


def drums(start, bars, big, hand_acc, lo, shout_bars=(), shout_at=0.0):
    for b in range(bars):
        t0 = start + b * B
        for k in big:
            S.add("big", t0 + k, 0.5, "C2", 110 if k == 0 else 92)
        for i in range(16):
            a = i * 0.25
            S.add("hand", t0 + a, 0.2, "C4", 92 if a in hand_acc else 48)
        for k in lo:
            S.add("low", t0 + k, 0.5, "C2", 100)
        if b in shout_bars:
            S.add("shout", t0 + shout_at, 0.4, "Bb2", 110)


# ================================================================ 인트로
S.add("roar", 0, 2.6, "C4", 110)
S.add("big", 0, 0.5, "C2", 120)
for i in range(8):
    S.add("hand", 2 + i * 0.25, 0.2, "C4", 50 + 8 * i)
S.add("shout", 3.0, 0.4, "Bb2", 115)

