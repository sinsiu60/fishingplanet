    [("E5", .5), ("G5", .5), ("A5", 1), ("G5", .75), ("E5", .25), ("D5", 1)],
    [("B4", 1.5), ("A4", .5), ("G4", .75), ("A4", .25), ("B4", 1)],
    [("E4", 2), ("r", .5), ("B3", .5), ("D4", .5), ("E4", .5)],
    [("A4", .75), ("B4", .25), ("D5", .75), ("E5", .25), ("G5", 2)],
