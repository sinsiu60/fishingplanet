# ================================================================ 위기 (낮은 북 8분 + 박마다 외침)
for name in S.loops:
    lst = S.crisis.setdefault(name, [])
    for k in range(16):
        for i in range(8):
            S.add("c_low", k * B + i * 0.5, 0.4, "C2", 100 if i % 2 == 0 else 80, into=lst)
        for a in (0, 2):
            S.add("c_shout", k * B + a, 0.35, "Bb2", 100, into=lst)

# ================================================================ 전환 (큰 북 굴림 + 멀리서 울음 + 외침)
