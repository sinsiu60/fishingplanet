    notes = []
    for i in range(15):
        S.add("big", i * 0.25, 0.3, "C2", 50 + 4 * i, into=notes)
    S.add("roar", 0, 2.0, "C4", 80, into=notes)
    S.add("shout", 3.5, 0.4, "Bb2", 115, into=notes)
    S.transitions[k] = {"beats": 4, "notes": notes}

